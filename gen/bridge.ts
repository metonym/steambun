// Generate Swift from bridge schemas.
//
//   frameworkSwift()      Bridge.gen.swift: the framework's ops (steambun/bridge.ts)
//   appSwift(bridge)      App.gen.swift: an app's own ops and events
//
// Each op becomes a method on a protocol the shell conforms to, so a
// missing handler is a compile error, and Xcode's fix-it writes the stub.
import {
  CORE_EVENTS,
  CORE_OPS,
  PAGE_OPS,
  SHELL_EVENTS,
  TEST_OPS,
} from "../bridge.ts";
import type { Bridge, Op, Ty } from "../schema.ts";

/** "menu.setKeys" → "menuSetKeys"; "screen.hz" → "ScreenHz" with `up`. */
export const ident = (s: string, up = false) => {
  const w = s.split(/[.\-_]/).filter(Boolean);
  const out = w.map((x, i) => (i || up ? x[0]!.toUpperCase() + x.slice(1) : x));
  return out.join("");
};

const q = (s: string) => JSON.stringify(s);

/** Every named struct reachable from `tys`, once, in the order first seen. */
function structs(tys: Ty<unknown>[]): Map<string, Ty<unknown>> {
  const out = new Map<string, Ty<unknown>>();
  function collect(x: Ty<unknown>) {
    if (x.of) collect(x.of);
    if (!x.name || !x.fields) return;
    for (const f of Object.values(x.fields)) collect(f);
    const had = out.get(x.name);
    if (had && had !== x) throw new Error(`steambun: two structs named ${x.name}`);
    out.set(x.name, x);
  }
  tys.forEach(collect);
  return out;
}

const opTys = (ops: Record<string, Op>) =>
  Object.values(ops).flatMap((o) => [o.args, o.result]);

const frameworkStructs = () =>
  structs([
    ...opTys(PAGE_OPS),
    ...opTys(CORE_OPS),
    ...opTys(TEST_OPS),
    ...Object.values(SHELL_EVENTS),
    ...Object.values(CORE_EVENTS),
  ]);

function writeStructs(w: (s?: string) => void, m: Map<string, Ty<unknown>>) {
  for (const [name, s] of m) {
    w(`struct ${name}: Codable {`);
    for (const [k, f] of Object.entries(s.fields!)) w(`  var ${k}: ${f.swift}`);
    w("}");
    w();
  }
}

function sig(k: string, o: Op): string {
  const a = o.args.swift === "Void" ? "" : `_ a: ${o.args.swift}`;
  const r = o.result.swift === "Void" ? "" : ` -> ${o.result.swift}`;
  return `func ${ident(k)}(${a})${r}`;
}

function dispatchCases(w: (s?: string) => void, ops: Record<string, Op>) {
  for (const [k, o] of Object.entries(ops)) {
    const call =
      o.args.swift === "Void"
        ? `${ident(k)}()`
        : `${ident(k)}(try bridgeDecode(${o.args.swift}.self, args))`;
    const r = o.result.swift;
    if (r === "Void") w(`    case ${q(k)}: ${call}; return nil`);
    else if (o.result.fields) w(`    case ${q(k)}: return try bridgeEncode(${call})`);
    else w(`    case ${q(k)}: return ${call}`);
  }
}

function emitters(w: (s?: string) => void, events: Record<string, Ty<unknown>>) {
  for (const [k, e] of Object.entries(events)) {
    w(`  func emit${ident(k, true)}(_ p: ${e.swift}) {`);
    w(`    guard let d = try? JSONEncoder().encode(p) else { return }`);
    w(`    emit(${q(k)}, String(decoding: d, as: UTF8.self))`);
    w("  }");
  }
}

export function frameworkSwift(): string {
  const L: string[] = [];
  const w = (s = "") => L.push(s);
  w("// Generated by steambun/gen from steambun/bridge.ts. Do not edit.");
  w();
  w("import Foundation");
  w();
  writeStructs(w, frameworkStructs());

  w("/// Page ops the shell supports. The page gets this list at load.");
  w(`let BRIDGE_PAGE_OPS = [${Object.keys(PAGE_OPS).map(q).join(", ")}]`);
  w();
  w("/// The shell implements one method per page op. Each runs on the main thread.");
  w("protocol BridgeHandlers: AnyObject {");
  for (const [k, o] of Object.entries(PAGE_OPS)) w(`  ${sig(k, o)}`);
  w("  /// The app's ops (App.gen.swift).");
  w("  func appDispatch(_ op: String, _ args: Any?) throws -> Any?");
  w("}");
  w();
  w("struct BridgeError: LocalizedError {");
  w("  let msg: String");
  w("  init(_ m: String) { msg = m }");
  w("  var errorDescription: String? { msg }");
  w("}");
  w();
  w("/// Decode a JSON value (from WebKit or JSONSerialization) into a struct.");
  w("func bridgeDecode<T: Decodable>(_ t: T.Type, _ v: Any?) throws -> T {");
  w("  let d = try JSONSerialization.data(withJSONObject: v ?? [String: Any](), options: .fragmentsAllowed)");
  w("  return try JSONDecoder().decode(t, from: d)");
  w("}");
  w();
  w("/// Encode a struct as a JSON value WebKit can pass to the page.");
  w("func bridgeEncode<T: Encodable>(_ v: T) throws -> Any {");
  w("  try JSONSerialization.jsonObject(with: JSONEncoder().encode(v), options: .fragmentsAllowed)");
  w("}");
  w();
  w("extension BridgeHandlers {");
  w("  /// Run a page op by name. Returns its JSON result, or nil for none.");
  w("  func bridgeDispatch(_ op: String, _ args: Any?) throws -> Any? {");
  w("    switch op {");
  dispatchCases(w, PAGE_OPS);
  w("    default: return try appDispatch(op, args)");
  w("    }");
  w("  }");
  w("}");
  w();
  w("/// Sends events to the page. The shell implements `emit(_:_:)`.");
  w("protocol BridgeEmitter: AnyObject {");
  w("  /// Deliver an event with a JSON payload to the page.");
  w("  func emit(_ name: String, _ json: String)");
  w("}");
  w();
  w("extension BridgeEmitter {");
  emitters(w, SHELL_EVENTS);
  w("}");
  w();
  w("/// Core ops on a native browser page. Switch over it: a new op in the");
  w("/// schema fails the build until the shell handles it.");
  w("enum CoreOp: String, CaseIterable {");
  for (const k of Object.keys(CORE_OPS)) w(`  case \`${k}\``);
  w("}");
  w();
  w("/// Test ops (steambun/test/harness.ts). Switch over it, as for CoreOp.");
  w("enum TestOp: String, CaseIterable {");
  for (const k of Object.keys(TEST_OPS)) w(`  case \`${k}\``);
  w("}");
  return L.join("\n") + "\n";
}

/** App.gen.swift for an app's bridge. With no bridge, an empty one. */
export function appSwift(app: Bridge | null, from: string): string {
  const ops = app?.ops ?? {};
  const events = app?.events ?? {};
  for (const k of Object.keys(ops))
    if (k in PAGE_OPS) throw new Error(`steambun: ${from}: op ${k} is the framework's`);
  for (const k of Object.keys(events))
    if (k in SHELL_EVENTS) throw new Error(`steambun: ${from}: event ${k} is the framework's`);
  const fw = frameworkStructs();
  const mine = structs([...opTys(ops), ...Object.values(events)]);
  for (const [n, s] of mine) {
    if (fw.get(n) === s) mine.delete(n);
    else if (fw.has(n)) throw new Error(`steambun: ${from}: struct ${n} is the framework's`);
  }

  const L: string[] = [];
  const w = (s = "") => L.push(s);
  w(`// Generated by steambun/gen from ${from}. Do not edit.`);
  w();
  w("import Foundation");
  w();
  writeStructs(w, mine);
  w("/// The app's page ops. The page gets them with the framework's.");
  w(`let APP_PAGE_OPS: [String] = [${Object.keys(ops).map(q).join(", ")}]`);
  w();
  if (Object.keys(ops).length) {
    w("/// One method per op in the app's bridge. Write them in an");
    w("/// `extension Shell { … }` in your Swift files. Each runs on the main thread.");
  } else {
    w("/// The app's bridge has no ops.");
  }
  w("protocol AppHandlers: AnyObject {");
  for (const [k, o] of Object.entries(ops)) w(`  ${sig(k, o)}`);
  w("}");
  w();
  w("extension Shell: AppHandlers {}");
  w();
  w("extension AppHandlers {");
  w("  func appDispatch(_ op: String, _ args: Any?) throws -> Any? {");
  w("    switch op {");
  dispatchCases(w, ops);
  w('    default: throw BridgeError("unknown op \\(op)")');
  w("    }");
  w("  }");
  w("}");
  if (Object.keys(events).length) {
    w();
    w("extension BridgeEmitter {");
    emitters(w, events);
    w("}");
  }
  return L.join("\n") + "\n";
}

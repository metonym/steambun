import { describe, expect, test } from "bun:test";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import {
  buildBundleDefine,
  buildImportMetaEnvDefine,
  filterPublicEnv,
  loadEnv,
  loadEnvFiles,
  parseEnvFile,
  toBunEnvPattern,
  toPublicPath,
} from "../src/env/loader";
import { generateEnvDts, writeEnvDts } from "../src/env/types";

describe("parseEnvFile", () => {
  test("skips blank lines and # comments", () => {
    expect(
      parseEnvFile(`
# comment
FOO=bar

BAZ=qux
`),
    ).toEqual({ FOO: "bar", BAZ: "qux" });
  });

  test("parses KEY=value and quoted values", () => {
    expect(parseEnvFile(`PLAIN=one\nDOUBLE="two"\nSINGLE='three'`)).toEqual({
      PLAIN: "one",
      DOUBLE: "two",
      SINGLE: "three",
    });
  });

  test("handles CR-LF lines", () => {
    expect(parseEnvFile("A=1\r\nB=2\r\n")).toEqual({ A: "1", B: "2" });
  });

  test("ignores keys without =", () => {
    expect(parseEnvFile("NOPE\nOK=yes")).toEqual({ OK: "yes" });
  });
});

describe("filterPublicEnv", () => {
  test("keeps only matching prefixes", () => {
    expect(
      filterPublicEnv({ VITE_A: "1", PUBLIC_B: "2", SECRET: "3", VITE: "4" }, [
        "VITE_",
        "PUBLIC_",
      ]),
    ).toEqual({ VITE_A: "1", PUBLIC_B: "2" });
  });
});

describe("buildImportMetaEnvDefine", () => {
  test("JSON-stringifies MODE/DEV/PROD/SSR/BASE_URL and public keys", () => {
    expect(
      buildImportMetaEnvDefine(
        { VITE_A: "1" },
        { mode: "development", command: "dev", base: "/" },
      ),
    ).toEqual({
      "import.meta.env.MODE": '"development"',
      "import.meta.env.DEV": "true",
      "import.meta.env.PROD": "false",
      "import.meta.env.SSR": "false",
      "import.meta.env.BASE_URL": '"/"',
      "import.meta.env.VITE_A": '"1"',
      "process.env.VITE_A": '"1"',
    });
  });
});

describe("buildBundleDefine", () => {
  const opts = {
    mode: "production",
    command: "build" as const,
    base: "/",
  };

  test("adds process.env.NODE_ENV from mode and keeps import.meta.env", () => {
    const define = buildBundleDefine({ VITE_A: "1" }, opts);
    expect(define["process.env.NODE_ENV"]).toBe('"production"');
    expect(define["import.meta.env.MODE"]).toBe('"production"');
    expect(define["import.meta.env.VITE_A"]).toBe('"1"');
    expect(define["process.env.VITE_A"]).toBe('"1"');
  });

  test("non-production mode sets NODE_ENV to development", () => {
    expect(
      buildBundleDefine({}, { ...opts, mode: "staging" })[
        "process.env.NODE_ENV"
      ],
    ).toBe('"development"');
  });

  test("merges user define; user NODE_ENV wins", () => {
    const define = buildBundleDefine({}, opts, {
      "process.env.NODE_ENV": '"staging"',
      MY_FLAG: '"on"',
    });
    expect(define["process.env.NODE_ENV"]).toBe('"staging"');
    expect(define.MY_FLAG).toBe('"on"');
  });

  test("user import.meta.env keys override env-file defines", () => {
    const define = buildBundleDefine({ PUBLIC_TITLE: "from-env" }, opts, {
      "import.meta.env.PUBLIC_TITLE": JSON.stringify("from config"),
    });
    expect(define["import.meta.env.PUBLIC_TITLE"]).toBe('"from config"');
  });
});

describe("loadEnv", () => {
  test("later files override earlier ones; process.env wins", async () => {
    const dir = mkdtempSync(join(tmpdir(), "steambun-env-"));
    writeFileSync(join(dir, ".env"), "A=from-env\nB=keep\n");
    writeFileSync(join(dir, ".env.local"), "A=from-local\n");
    mkdirSync(dir, { recursive: true });
    const prev = process.env.A;
    process.env.A = "from-process";
    try {
      const env = await loadEnv("development", dir);
      expect(env.A).toBe("from-process");
      expect(env.B).toBe("keep");
    } finally {
      if (prev === undefined) delete process.env.A;
      else process.env.A = prev;
    }
  });
});

describe("loadEnvFiles", () => {
  test("reads .env files and ignores process.env", async () => {
    const dir = mkdtempSync(join(tmpdir(), "steambun-env-files-"));
    writeFileSync(join(dir, ".env"), "PUBLIC_FROM_FILE=yes\n");
    const prev = process.env.PUBLIC_FROM_PROCESS;
    process.env.PUBLIC_FROM_PROCESS = "shell";
    try {
      const files = await loadEnvFiles("development", dir);
      expect(files).toEqual({ PUBLIC_FROM_FILE: "yes" });
      expect(files.PUBLIC_FROM_PROCESS).toBeUndefined();
    } finally {
      if (prev === undefined) delete process.env.PUBLIC_FROM_PROCESS;
      else process.env.PUBLIC_FROM_PROCESS = prev;
    }
  });
});

describe("generateEnvDts", () => {
  test("emits a client reference and no extra fields when there are no public keys", () => {
    expect(
      generateEnvDts([]),
    ).toBe(`// Generated by steambun from envPrefix-matched keys. Do not edit.
/// <reference types="steambun/client" />
`);
  });

  test("adds sorted extra keys and skips builtins", () => {
    expect(
      generateEnvDts(["PUBLIC_B", "MODE", "VITE_A", "PUBLIC_B"]),
    ).toBe(`// Generated by steambun from envPrefix-matched keys. Do not edit.
/// <reference types="steambun/client" />

export {};

declare global {
  interface ImportMetaEnv {
    readonly PUBLIC_B: string;
    readonly VITE_A: string;
  }
}
`);
  });

  test("quotes keys that are not identifiers", () => {
    expect(generateEnvDts(["PUBLIC-X"])).toContain(
      '  readonly "PUBLIC-X": string;',
    );
  });
});

describe("writeEnvDts", () => {
  test("writes .steambun/env.d.ts and removes a legacy root file", async () => {
    const dir = mkdtempSync(join(tmpdir(), "steambun-env-dts-"));
    writeFileSync(join(dir, "steambun-env.d.ts"), "// leftover\n");
    const path = await writeEnvDts(dir, { PUBLIC_GREETING: "hello" });
    expect(path).toBe(join(dir, ".steambun", "env.d.ts"));
    expect(readFileSync(path, "utf8")).toContain(
      "readonly PUBLIC_GREETING: string;",
    );
    expect(existsSync(join(dir, "steambun-env.d.ts"))).toBe(false);
  });
});

describe("toBunEnvPattern", () => {
  test("single prefix becomes PREFIX*", () => {
    expect(toBunEnvPattern(["PUBLIC_"])).toBe("PUBLIC_*");
  });

  test("multiple prefixes are skipped", () => {
    expect(toBunEnvPattern(["VITE_", "PUBLIC_"])).toBeUndefined();
  });
});

describe("toPublicPath", () => {
  test("root base is omitted", () => {
    expect(toPublicPath("/")).toBeUndefined();
  });

  test("adds a trailing slash when missing", () => {
    expect(toPublicPath("/app")).toBe("/app/");
    expect(toPublicPath("/app/")).toBe("/app/");
  });
});

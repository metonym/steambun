import { existsSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { basename, join } from "node:path";
import { isPlainObject } from "../util/guards";
import {
  findConfigFile,
  type LoadConfigOptions,
  loadRawConfigExport,
} from "./loader";
import type { Command, Mode, UserConfig } from "./types";
import { viteConfigToUserConfig } from "./vite";

const IDENTIFIER_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function keyPath(base: string, key: string): string {
  if (IDENTIFIER_RE.test(key)) return base ? `${base}.${key}` : key;
  return `${base}["${key}"]`;
}

// Emits JS literal syntax (not JSON) so functions and regexps can be inlined
// verbatim, rather than silently dropped like `JSON.stringify` would.
function serializeValue(
  value: unknown,
  indent: number,
  path: string,
  functions: string[],
  dropped: string[],
): string | undefined {
  if (value === undefined) return undefined;
  if (value === null) return "null";
  if (typeof value === "string") return JSON.stringify(value);
  if (typeof value === "number" || typeof value === "boolean") {
    return String(value);
  }
  if (typeof value === "function") {
    functions.push(path);
    return value.toString();
  }
  if (value instanceof RegExp) return value.toString();

  const pad = "  ".repeat(indent);
  const childPad = "  ".repeat(indent + 1);

  if (Array.isArray(value)) {
    const items: string[] = [];
    value.forEach((item, i) => {
      const itemPath = `${path}[${i}]`;
      const s = serializeValue(item, indent + 1, itemPath, functions, dropped);
      items.push(`${childPad}${s ?? "undefined"}`);
    });
    if (items.length === 0) return "[]";
    return `[\n${items.join(",\n")}\n${pad}]`;
  }

  if (isPlainObject(value)) {
    const entries: string[] = [];
    for (const [key, val] of Object.entries(value)) {
      const s = serializeValue(
        val,
        indent + 1,
        keyPath(path, key),
        functions,
        dropped,
      );
      if (s === undefined) continue;
      const keyStr = IDENTIFIER_RE.test(key) ? key : JSON.stringify(key);
      entries.push(`${childPad}${keyStr}: ${s}`);
    }
    if (entries.length === 0) return "{}";
    return `{\n${entries.join(",\n")}\n${pad}}`;
  }

  dropped.push(path);
  return undefined;
}

function serializeConfig(config: UserConfig): {
  source: string;
  functions: string[];
  dropped: string[];
} {
  const functions: string[] = [];
  const dropped: string[] = [];
  const source = serializeValue(config, 0, "", functions, dropped) ?? "{}";
  return { source, functions, dropped };
}

/**
 * Converts a `vite.config.*` in `root` into `steambun.config.ts`, printing
 * one warning per unsupported key. Never overwrites an existing steambun
 * config. `root` must be absolute — the CLI resolves it once in `main()`.
 */
export async function migrate(root: string): Promise<void> {
  const found = findConfigFile(root);
  if (found?.kind === "steambun") {
    throw new Error(
      "[steambun] A steambun config already exists — not overwriting it.",
    );
  }
  if (found?.kind !== "vite") {
    throw new Error("[steambun] No vite.config.* found in this project.");
  }

  const ignoredKeys: string[] = [];
  const warn = (msg: string) => {
    const match = msg.match(/Vite config key "([^"]+)" is not supported/);
    if (match?.[1]) ignoredKeys.push(match[1]);
  };

  const buildRaw = await loadRawConfigExport(found.path, {
    command: "build",
    mode: "production",
  });
  const buildConfig = viteConfigToUserConfig(
    (buildRaw as Record<string, unknown>) ?? {},
    warn,
  );

  // Vite's own convention is `{ command: "serve", mode: "development" }` for
  // dev, distinct from steambun's `Command` union — cast rather than widen
  // `loadRawConfigExport`'s signature, which is shared with `loadConfig`.
  const devEnv = {
    command: "serve" as unknown as Command,
    mode: "development" as Mode,
  } satisfies Pick<LoadConfigOptions, "command" | "mode">;
  const devRaw = await loadRawConfigExport(found.path, devEnv);
  const devConfig = viteConfigToUserConfig(
    (devRaw as Record<string, unknown>) ?? {},
    () => {},
  );

  const { source, functions, dropped } = serializeConfig(buildConfig);
  const { source: devSource } = serializeConfig(devConfig);
  const divergent = source !== devSource;

  const outPath = join(root, "steambun.config.ts");
  if (existsSync(outPath)) {
    throw new Error(
      `[steambun] ${outPath} already exists — not overwriting it.`,
    );
  }

  const headerLines = [
    `// Generated by \`steambun migrate\` from ${basename(found.path)}.`,
  ];
  if (ignoredKeys.length > 0) {
    headerLines.push(`// Ignored Vite keys: ${ignoredKeys.join(", ")}`);
  }
  if (functions.length > 0) {
    headerLines.push(`// Inlined functions to review: ${functions.join(", ")}`);
  }

  const fileSource = `${headerLines.join("\n")}
import { defineConfig } from "steambun";

export default defineConfig(${source});
`;

  await writeFile(outPath, fileSource, "utf8");

  for (const path of functions) {
    console.log(
      `[steambun] migrate: inlined function at ${path} — review it, it may reference variables from vite.config.*`,
    );
  }
  for (const path of dropped) {
    console.log(
      `[steambun] migrate: dropped unsupported value at ${path} — it was replaced with undefined.`,
    );
  }
  if (divergent) {
    console.log(
      "[steambun] migrate: vite.config.* returns different values for dev and build; the production result was written — merge dev-only settings by hand",
    );
  }

  console.log(`[steambun] wrote steambun.config.ts from ${found.path}`);
}

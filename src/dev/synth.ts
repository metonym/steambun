import { generatePluginWrapperSource } from "./plugin-wrapper";

export interface SynthResult {
  dir: string;
  bunfigPath: string;
  servePath: string;
}

const HEADER =
  "// Auto-generated by steambun. Do not edit — regenerated on every dev run.";

/** Shared shape of the alias/vite-suffix plugin modules: import one factory
 * from `steambun/runtime` and re-export its call. */
function runtimePlugin(factory: string, ...args: unknown[]): string {
  return `${HEADER}
import { ${factory} } from "steambun/runtime";
export default ${factory}(${args.map((arg) => JSON.stringify(arg)).join(", ")});
`;
}

/** Writes a generated file (only if its content changed) and records its
 * path for the bunfig `plugins` list. */
async function emitPlugin(
  pluginPaths: string[],
  path: string,
  src: string,
): Promise<void> {
  pluginPaths.push(path);
  await writeIfChanged(path, src);
}

// serve.ts stays thin: static HTML imports (required for Bun's bundler to
// associate them) plus a call back into loadConfig, so middleware/plugin
// functions stay intact instead of needing to be serialized.
export async function synthesizeDevServer(
  config: ResolvedConfig,
  htmlEntries: HtmlEntry[],
  publicEnvDefine: Record<string, string>,
): Promise<SynthResult> {
  const dir = join(config.root, STEAMBUN_DIR_NAME);
  await mkdir(dir, { recursive: true });

  const pluginPaths: string[] = [];
  const alias = config.resolve?.alias;
  if (alias && Object.keys(alias).length > 0) {
    await emitPlugin(
      pluginPaths,
      join(dir, "alias-plugin.ts"),
      runtimePlugin("createAliasPlugin", alias, config.root),
    );
  }

  if (config.resolve?.viteSuffixes) {
    await emitPlugin(
      pluginPaths,
      join(dir, "vite-suffix-plugin.ts"),
      runtimePlugin("createViteSuffixPlugin"),
    );
  }

  await emitPlugin(
    pluginPaths,
    join(dir, "env-plugin.ts"),
    generateEnvPluginSource(publicEnvDefine),
  );

  if (config.configFile && !isTomlConfigPath(config.configFile)) {
    const configSpecifier = toSpecifier(dir, config.configFile);
    for (const [index, plugin] of (config.plugins ?? []).entries()) {
      if (!isBunPlugin(plugin)) continue;
      await emitPlugin(
        pluginPaths,
        join(dir, `plugin-${index}.ts`),
        generatePluginWrapperSource(
          configSpecifier,
          index,
          config.command,
          config.mode,
        ),
      );
    }
  }

  const bunfigPath = join(dir, "bunfig.toml");
  await writeIfChanged(
    bunfigPath,
    serializeMergedBunfig(
      (await loadUserBunfigForMerge(config, dir)) ?? {},
      pluginPaths.map((path) => toSpecifier(dir, path)),
      toBunEnvPattern(config.envPrefix),
    ),
  );

  const servePath = join(dir, "serve.ts");
  await writeIfChanged(
    servePath,
    generateServeSource(config, htmlEntries, dir),
  );

  return { dir, bunfigPath, servePath };
}

async function loadUserBunfigForMerge(
  config: ResolvedConfig,
  dir: string,
): Promise<Record<string, unknown> | undefined> {
  const path =
    config.configFile && isTomlConfigPath(config.configFile)
      ? config.configFile
      : join(config.root, "bunfig.toml");
  if (!existsSync(path)) return undefined;
  const raw = parseBunfigToml(await Bun.file(path).text());
  return relocateBunfigPaths(raw, config.root, dir);
}

export function generateServeSource(
  config: ResolvedConfig,
  htmlEntries: HtmlEntry[],
  dir: string,
): string {
  const htmlImports = htmlEntries
    .map(
      (entry, i) => `import entry_${i} from "${toSpecifier(dir, entry.file)}";`,
    )
    .join("\n");

  const htmlRouteEntries = htmlEntries
    .map(
      (entry, i) =>
        `  ${JSON.stringify(htmlServePath(entry, config.appType))}: entry_${i},`,
    )
    .join("\n");

  const configFileSpecifier = config.configFile
    ? toSpecifier(dir, config.configFile)
    : null;

  return `${HEADER}
${htmlImports}
import { loadConfig } from "steambun";
import {
  createApp,
  displayServerUrls,
  hostnameFromHost,
  openBrowser,
  resolveOpenUrl,
  serveWithPortRetry,
  tlsFromHttps,
} from "steambun/runtime";

const startedAt = performance.now();

const config = await loadConfig({
  root: ${JSON.stringify(config.root)},
  command: "dev",
  mode: ${JSON.stringify(config.mode)},
  ${configFileSpecifier ? `configFile: ${JSON.stringify(config.configFile)},` : ""}
});

const app = await createApp({
  config,
  mode: "dev",
  htmlRoutes: {
${htmlRouteEntries}
  },
});

${SERVER_ENV_DECODER_SOURCE}
const { port, host, strictPort, open } = serverOverridesFromEnv(process.env, {
  port: config.server.port,
  host: config.server.host,
  strictPort: config.server.strictPort,
  open: config.server.open,
});

const server = serveWithPortRetry(
  {
    port,
    hostname: hostnameFromHost(host),
    tls: tlsFromHttps(config.server.https, config.root),
    ...app.serveOptions,
  },
  { strictPort, label: "dev" },
);

const { local, network } = displayServerUrls(server.url);
const elapsed = Math.round(performance.now() - startedAt);
console.log(\`[steambun] dev server ready in \${elapsed}ms\`);
console.log(\`  Local:   \${local}\`);
for (const url of network) console.log(\`  Network: \${url}\`);
const openUrl = resolveOpenUrl(local, open);
if (openUrl) openBrowser(openUrl);
`;
}

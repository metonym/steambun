import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import {
  isTomlConfigPath,
  parseBunfigToml,
  relocateBunfigPaths,
  serializeMergedBunfig,
} from "../config/bunfig";
import type { ResolvedConfig } from "../config/types";
import { toBunEnvPattern } from "../env/loader";
import { isBunPlugin } from "../util/plugins";
import { toImportSpecifier as toSpecifier } from "../util/specifier";
import { type HtmlEntry, htmlServePath } from "./discover";
import { generateEnvPluginSource } from "./env-plugin";
import { generatePluginWrapperSource } from "./plugin-wrapper";

export const STEAMBUN_DIR_NAME = ".steambun";

export interface SynthResult {
  dir: string;
  bunfigPath: string;
  servePath: string;
}

export function generateBunfigSource(
  pluginSpecifiers: string[],
  envPattern: `${string}*` | undefined,
  userBunfig?: Record<string, unknown>,
): string {
  return serializeMergedBunfig(userBunfig ?? {}, pluginSpecifiers, envPattern);
}

export function generateAliasPluginSource(
  alias: Record<string, string>,
  root: string,
): string {
  return `// Auto-generated by steambun. Do not edit — regenerated on every dev run.
import { createAliasPlugin } from "steambun/runtime";
export default createAliasPlugin(${JSON.stringify(alias)}, ${JSON.stringify(root)});
`;
}

// serve.ts stays thin: static HTML imports (required for Bun's bundler to
// associate them) plus a call back into loadConfig, so middleware/plugin
// functions stay intact instead of needing to be serialized.
export async function synthesizeDevServer(
  config: ResolvedConfig,
  htmlEntries: HtmlEntry[],
  publicEnvDefine: Record<string, string>,
): Promise<SynthResult> {
  const dir = join(config.root, STEAMBUN_DIR_NAME);
  await mkdir(dir, { recursive: true });

  const pluginPaths: string[] = [];
  const alias = config.resolve?.alias;
  if (alias && Object.keys(alias).length > 0) {
    const aliasPluginPath = join(dir, "alias-plugin.ts");
    pluginPaths.push(aliasPluginPath);
    await writeFile(
      aliasPluginPath,
      generateAliasPluginSource(alias, config.root),
      "utf8",
    );
  }

  const envPluginPath = join(dir, "env-plugin.ts");
  await writeFile(
    envPluginPath,
    generateEnvPluginSource(publicEnvDefine),
    "utf8",
  );
  pluginPaths.push(envPluginPath);

  if (config.configFile && !isTomlConfigPath(config.configFile)) {
    const configSpecifier = toSpecifier(dir, config.configFile);
    for (const [index, plugin] of (config.plugins ?? []).entries()) {
      if (!isBunPlugin(plugin)) continue;
      const wrapperPath = join(dir, `plugin-${index}.ts`);
      pluginPaths.push(wrapperPath);
      await writeFile(
        wrapperPath,
        generatePluginWrapperSource(
          configSpecifier,
          index,
          config.command,
          config.mode,
        ),
        "utf8",
      );
    }
  }

  const bunfigPath = join(dir, "bunfig.toml");
  await writeFile(
    bunfigPath,
    generateBunfigSource(
      pluginPaths.map((path) => toSpecifier(dir, path)),
      toBunEnvPattern(config.envPrefix),
      await loadUserBunfigForMerge(config, dir),
    ),
    "utf8",
  );

  const servePath = join(dir, "serve.ts");
  await writeFile(
    servePath,
    generateServeSource(config, htmlEntries, dir),
    "utf8",
  );

  return { dir, bunfigPath, servePath };
}

async function loadUserBunfigForMerge(
  config: ResolvedConfig,
  dir: string,
): Promise<Record<string, unknown> | undefined> {
  const path =
    config.configFile && isTomlConfigPath(config.configFile)
      ? config.configFile
      : join(config.root, "bunfig.toml");
  if (!existsSync(path)) return undefined;
  const raw = parseBunfigToml(await Bun.file(path).text());
  return relocateBunfigPaths(raw, config.root, dir);
}

function generateServeSource(
  config: ResolvedConfig,
  htmlEntries: HtmlEntry[],
  dir: string,
): string {
  const htmlImports = htmlEntries
    .map(
      (entry, i) => `import entry_${i} from "${toSpecifier(dir, entry.file)}";`,
    )
    .join("\n");

  const htmlRouteEntries = htmlEntries
    .map(
      (entry, i) =>
        `  ${JSON.stringify(htmlServePath(entry, config.appType))}: entry_${i},`,
    )
    .join("\n");

  const configFileSpecifier = config.configFile
    ? toSpecifier(dir, config.configFile)
    : null;

  return `// Auto-generated by steambun. Do not edit — regenerated on every dev run.
${htmlImports}
import { loadConfig } from "steambun";
import {
  addPublicDirRoutes,
  composeServerMiddleware,
  createErrorHandler,
  createProxyRouteHandler,
  createProxyWebSocketHandlers,
  displayServerUrl,
  hostnameFromHost,
  loadApiRoutes,
  openBrowser,
  resolveOpenUrl,
  tlsFromHttps,
  withMiddleware,
} from "steambun/runtime";

const config = await loadConfig({
  root: ${JSON.stringify(config.root)},
  command: "dev",
  mode: ${JSON.stringify(config.mode)},
  ${configFileSpecifier ? `configFile: ${JSON.stringify(config.configFile)},` : ""}
});

const middleware = composeServerMiddleware(config.server ?? {}, config.middleware);
const routes = {
${htmlRouteEntries}
};

if (config.publicDir) {
  await addPublicDirRoutes(routes, config.publicDir);
}

let hasWsProxy = false;
for (const [prefix, entry] of Object.entries(config.server?.proxy ?? {})) {
  const handler = withMiddleware(middleware, createProxyRouteHandler(prefix, entry));
  routes[prefix] = handler;
  routes[prefix.endsWith("/") ? \`\${prefix}*\` : \`\${prefix}/*\`] = handler;
  if (typeof entry === "object" && entry.ws) hasWsProxy = true;
}

if (config.api) {
  const apiRoutes = await loadApiRoutes(config.api);
  for (const [path, handler] of Object.entries(apiRoutes)) {
    if (typeof handler === "function") {
      routes[path] = withMiddleware(middleware, handler);
    } else {
      const wrapped = {};
      for (const [method, fn] of Object.entries(handler)) {
        wrapped[method] = withMiddleware(middleware, fn);
      }
      routes[path] = wrapped;
    }
  }
}

const server = Bun.serve({
  port: config.server.port,
  hostname: hostnameFromHost(config.server.host),
  development: { hmr: true, console: true },
  id: "steambun-dev",
  routes,
  error: createErrorHandler(true),
  idleTimeout: config.server.idleTimeout,
  maxRequestBodySize: config.server.maxRequestBodySize,
  tls: tlsFromHttps(config.server.https, config.root),
  ...(hasWsProxy ? { websocket: createProxyWebSocketHandlers() } : {}),
});

const displayUrl = displayServerUrl(server.url);
console.log(\`[steambun] dev server ready at \${displayUrl}\`);
const openUrl = resolveOpenUrl(displayUrl, config.server.open);
if (openUrl) openBrowser(openUrl);
`;
}

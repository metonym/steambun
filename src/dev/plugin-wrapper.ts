// bunfig.toml's plugins array only accepts file paths exporting a single
// plugin object (see env-plugin.ts). A user's plugins live as values in
// their config, not standalone modules, so each gets a generated wrapper
// that re-resolves the config and re-exports plugins[index].
export function generatePluginWrapperSource(
  configSpecifier: string,
  index: number,
  command: string,
  mode: string,
): string {
  return `// Auto-generated by steambun. Do not edit — regenerated on every dev run.
import configExport from "${configSpecifier}";

const resolved =
  typeof configExport === "function"
    ? await configExport({ command: ${JSON.stringify(command)}, mode: ${JSON.stringify(mode)} })
    : configExport;

export default (resolved?.plugins ?? [])[${index}];
`;
}

import { isAbsolute, join, relative, sep } from "node:path";

/** steambun's generated-file directory (types, synthesized dev server, plugins), relative to the project root. */
export const STEAMBUN_DIR_NAME = ".steambun";

/** The bundled production server `build` writes into `outDir`; it embeds the config, so it is never served. */
export const DIST_SERVER_FILE = "server.js";

/** First line of every file steambun generates. */
export const GENERATED_HEADER = "// Auto-generated by steambun. Do not edit.";

/** `p` as-is if absolute, else resolved against `root`. */
export function resolveFrom(root: string, p: string): string {
  return isAbsolute(p) ? p : join(root, p);
}

/** Whether `path` is strictly inside `root` (not `root` itself). */
export function isInside(root: string, path: string): boolean {
  const rel = relative(root, path);
  return (
    rel !== "" &&
    rel !== ".." &&
    !rel.startsWith(`..${sep}`) &&
    !isAbsolute(rel)
  );
}
